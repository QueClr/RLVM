package rlvm.nat;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import org.junit.jupiter.api.Test;

/**
 * Replays results computed by the official Lean 4.36.0 kernel ({@code Lean.Kernel.whnf}, i.e.
 * {@code reduce_nat}) under several values of {@code LEAN_NAT_MAX_SIZE}; the file is generated by
 * {@code src/test/lean/gen-official-vectors.sh}. This is ground truth, not our reading of the C++ code.
 */
class OfficialVectorsTest {
    private static final BigInteger P61 = BigInteger.valueOf(2305843009213693951L);

    private static BigInteger arg(String tok) {
        char c = tok.charAt(0);
        if (c == 'p') {
            return BigInteger.ONE.shiftLeft(Integer.parseInt(tok.substring(1)));
        }
        if (c == 'm') {
            return BigInteger.ONE.shiftLeft(Integer.parseInt(tok.substring(1))).subtract(BigInteger.ONE);
        }
        if (c == 'q') {
            return BigInteger.ONE.shiftLeft(Integer.parseInt(tok.substring(1))).add(BigInteger.ONE);
        }
        return new BigInteger(tok);
    }

    @Test
    void agreesWithTheOfficialKernel() throws Exception {
        InputStream in = getClass().getResourceAsStream("official-nat-vectors.txt");
        assertNotNull(in, "golden file");
        HashMap<Long, NatStore> stores = new HashMap<>();
        HashMap<String, Integer> perOp = new HashMap<>();
        int lines = 0;
        int errors = 0;
        try (BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
            String line;
            while ((line = r.readLine()) != null) {
                if (line.isEmpty() || line.charAt(0) == '#') {
                    continue;
                }
                String[] t = line.split(" ");
                long max = Long.parseLong(t[0]);
                NatStore s = stores.get(max);
                if (s == null) {
                    NatStore base = NatStore.newBase(max);
                    base.freeze();
                    s = base.newOverlay();
                    stores.put(max, s);
                }
                int op = NatOp.ofShortName(t[1]);
                assertTrue(op != 0 && NatOp.isOfficial(op), line);
                assertEquals(NatOp.arity(op) + 3, t.length, line);
                String expected = t[t.length - 1];
                int mark = s.mark();
                long a = Nat.ofBigInteger(s, arg(t[2]));
                long res;
                if (NatOp.arity(op) == 1) {
                    res = Nat.apply1(s, op, a);
                } else {
                    long b = Nat.ofBigInteger(s, arg(t[3]));
                    res = Nat.apply2(s, op, a, b);
                }
                check(s, op, res, expected, line);
                if (expected.charAt(0) == '!') {
                    errors++;
                }
                perOp.merge(t[1], 1, Integer::sum);
                s.truncate(mark);
                if (s.bytesUsed() == 0 && lines % 64 == 0) {
                    s.reset(); // give back the slab after the 128 MiB cases
                }
                lines++;
            }
        }
        assertTrue(lines > 70000, "vectors read: " + lines);
        assertTrue(errors > 5000, "guard cases read: " + errors);
        assertEquals(15, perOp.size(), "all 15 accelerated functions are covered: " + perOp);
    }

    private static void check(NatStore s, int op, long res, String expected, String line) {
        String shown = line.length() > 300 ? line.substring(0, 300) + "..." : line;
        if (expected.equals("!size")) {
            assertEquals(Nat.TOO_BIG, res, shown);
        } else if (expected.equals("!count")) {
            assertEquals(Nat.COUNT_TOO_BIG, res, shown);
        } else if (expected.equals("=true") || expected.equals("=false")) {
            assertTrue(NatOp.isPredicate(op), shown);
            assertEquals(expected.equals("=true") ? 1 : 0, res, shown);
        } else if (expected.startsWith("=#")) {
            assertTrue(Nat.isBig(res), shown);
            int colon = expected.indexOf(':');
            long bits = Long.parseLong(expected.substring(2, colon));
            assertEquals(bits, Nat.bitLength(s, res), shown);
            assertEquals(new BigInteger(expected.substring(colon + 1)), Nat.toBigInteger(s, res).mod(P61), shown);
        } else if (expected.charAt(0) == '=') {
            assertTrue(!NatOp.isPredicate(op), shown);
            TestSupport.assertOutcome(s, new BigInteger(expected.substring(1)), res, shown);
        } else {
            fail("unexpected golden result: " + shown);
        }
    }
}
