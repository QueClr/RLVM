#!/usr/bin/env bash
# Regenerates src/test/resources/rlvm/nat/official-nat-vectors.txt with the official Lean kernel.
# Needs the Lean toolchain v4.36.0 installed by elan (host or container); nothing else.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
sysroot="${LEAN_SYSROOT:-$HOME/.elan/toolchains/leanprover--lean4---v4.36.0}"
out="$here/../resources/rlvm/nat/official-nat-vectors.txt"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
python3 -I "$here/gen_nat_inputs.py" full > "$tmp/full.txt"
python3 -I "$here/gen_nat_inputs.py" sized > "$tmp/sized.txt"
{
  echo "# Generated by gen-official-vectors.sh with $("$sysroot/bin/lean" --version)"
  echo "# line: <LEAN_NAT_MAX_SIZE> <op> <a> [<b>] <result>; see OfficialNatVectors.lean for the syntax"
  "$sysroot/bin/lean" --run "$here/OfficialNatVectors.lean" "$sysroot" 134217728 "$tmp/full.txt"
  LEAN_NAT_MAX_SIZE=64 "$sysroot/bin/lean" --run "$here/OfficialNatVectors.lean" "$sysroot" 64 "$tmp/full.txt"
  for mx in 8 16 20 100 4096; do
    LEAN_NAT_MAX_SIZE=$mx "$sysroot/bin/lean" --run "$here/OfficialNatVectors.lean" "$sysroot" $mx "$tmp/sized.txt"
  done
} > "$out.tmp"
mv "$out.tmp" "$out"
wc -l "$out"

# String literals: kernel def-eq of a literal with String.ofList [Char.ofNat ...]
sout="$here/../resources/rlvm/nat/official-str-vectors.txt"
python3 -I "$here/gen_str_inputs.py" > "$tmp/str.txt"
{
  echo "# Generated by gen-official-vectors.sh with $("$sysroot/bin/lean" --version)"
  echo "# line: <utf-8 hex|-> <list c> <list d> <isDefEq(lit, String.ofList c)> <isDefEq(lit, String.ofList d)>"
  "$sysroot/bin/lean" --run "$here/OfficialStrVectors.lean" "$sysroot" "$tmp/str.txt"
} > "$sout.tmp"
mv "$sout.tmp" "$sout"
wc -l "$sout"
