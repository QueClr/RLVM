#!/usr/bin/env bash
# scripts/arena/test-in-docker.sh - build and run the arena checker definition (rlvm.yaml) end to
# end, the way the arena would, inside the rlvm-arena container.                  (run on the host)
#
#   scripts/arena/test-in-docker.sh [--reuse] [--force-zlib] [--strict] [-- build.sh options...]
#
# 1. A clean copy of what a git checkout contains (parent pom, env.sh, modules without target/,
#    scripts/) is made in work/arena-e2e/src. It has no .toolchain/: the build must fetch everything.
# 2. In the container (network on, 8 CPUs / 16 GB like the runner), with cwd = that copy:
#       sh -c "<build: line of rlvm.yaml>"
#    i.e. scripts/arena/build.sh: GraalVM + Maven download with checksum verification, Maven online,
#    native image, verification of the image.
# 3. rlvm.yaml is validated against the arena's schema (refs/lean-kernel-arena/schemas/checker.json).
# 4. The `run:` line is executed like the arena does (sh -c, cwd = the copy, $IN, LC_ALL=C, under
#    perf stat + GNU time) on a few published tests, with network off. Each must end with the
#    expected verdict (0 for a good test, 1 for a bad one); a decline (2) is tolerated unless
#    --strict is given; a wrong verdict or any other status fails.
#
#   --reuse        keep work/arena-e2e/src/.toolchain from the previous run (skips the 335 MB download)
#   --strict       a decline fails too (use once the pipeline passes the published tests)
#   --force-zlib   make the build compile zlib from source even though the image has zlib (tests the
#                  fall-back for machines without zlib development files); the script then checks
#                  that the binary does not depend on libz.so
#   -- ARGS        appended to the build line, e.g. -- --modules rlvm-cli  while another module is
#                  being rewritten and does not compile
#
# Log: work/logs/rlvm/arena-e2e.log. Exit status 0 only if every step succeeded.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
E2E="$ROOT/work/arena-e2e"
SRC="$E2E/src"
LOG="$ROOT/work/logs/rlvm/arena-e2e.log"
YAML_REL="scripts/arena/rlvm.yaml"

reuse=0
force_zlib=0
strict=0
build_extra=()
while [ "$#" -gt 0 ]; do
  case "$1" in
    --reuse) reuse=1; shift ;;
    --force-zlib) force_zlib=1; shift ;;
    --strict) strict=1; shift ;;
    -h|--help) sed -n '2,27p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    --) shift; build_extra=("$@"); break ;;
    *) echo "test-in-docker.sh: unknown option: $1" >&2; exit 2 ;;
  esac
done

say() { echo "arena-e2e: $*" | tee -a "$LOG" >&2; }
mkdir -p "$E2E" "$(dirname "$LOG")"
: > "$LOG"

# The build and the runs use the eight cores of the arena-shaped container: hold the measurement
# lock (bench/track/ladder.py, scripts/platform-matrix.py) so that this test does not run into
# somebody's measurement, nor theirs into the instruction counts printed below.
if command -v flock >/dev/null 2>&1; then
  mkdir -p "$ROOT/work/perf-history"
  exec 8>"$ROOT/work/perf-history/.ladder.lock"
  if ! flock -n 8; then
    say "a measurement holds work/perf-history/.ladder.lock; waiting for it"
    flock 8
  fi
fi

# --- 1. clean copy --------------------------------------------------------------------------------
keep=""
if [ "$reuse" = 1 ] && [ -d "$SRC/.toolchain" ]; then
  keep="$E2E/toolchain.keep"
  rm -rf "$keep"; mv "$SRC/.toolchain" "$keep"
fi
rm -rf "$SRC"; mkdir -p "$SRC"
modules="$(sed -n 's:.*<module>\(.*\)</module>.*:\1:p' "$ROOT/pom.xml" | paste -sd' ' -)"
# shellcheck disable=SC2086
( cd "$ROOT" && tar --exclude=target -cf - pom.xml env.sh scripts $modules ) | tar -C "$SRC" -xf -
[ -z "$keep" ] || mv "$keep" "$SRC/.toolchain"
say "clean copy in $SRC ($(find "$SRC" -path "$SRC/.toolchain" -prune -o -type f -print | wc -l) files; toolchain $([ -d "$SRC/.toolchain" ] && echo reused || echo absent))"

build_line="$(sed -n 's/^build:[[:space:]]*//p' "$SRC/$YAML_REL" | head -n 1)"
run_line="$(sed -n 's/^run:[[:space:]]*//p' "$SRC/$YAML_REL" | head -n 1)"
[ -n "$build_line" ] && [ -n "$run_line" ] || { say "no build:/run: line in $YAML_REL"; exit 1; }
if [ "${#build_extra[@]}" -gt 0 ]; then
  build_line="$build_line$(printf ' %q' "${build_extra[@]}")"
fi
say "build: $build_line"
say "run:   $run_line"

# --- 2. build ---------------------------------------------------------------------------------------
t0="$(date +%s)"
build_rc=0
"$ROOT/bench/arena-docker.sh" --arena-limits -w "$SRC" -e "RLVM_ARENA_FORCE_ZLIB=$force_zlib" \
    sh -c "$build_line" >> "$LOG" 2>&1 || build_rc=$?
say "build finished with status $build_rc after $(( $(date +%s) - t0 )) s"
if [ "$build_rc" != 0 ]; then
  tail -n 30 "$LOG" >&2
  exit 1
fi

# --- 3 + 4. schema, run -------------------------------------------------------------------------------
cat > "$E2E/inner.sh" <<'EOF'
#!/usr/bin/env bash
# Generated by scripts/arena/test-in-docker.sh; runs inside the container, cwd = the clean copy.
set -uo pipefail
ROOT="$1"; run_line="$2"; force_zlib="$3"; strict="$4"
fail=0
python3 -I - "$ROOT/refs/lean-kernel-arena/schemas/checker.json" scripts/arena/rlvm.yaml <<'PY' || fail=1
import json, sys, yaml, jsonschema
schema = json.load(open(sys.argv[1]))
doc = yaml.safe_load(open(sys.argv[2]))
jsonschema.validate(doc, schema)
print("schema: rlvm.yaml is a valid checker definition (keys: %s)" % ", ".join(sorted(doc)))
PY
echo "binary: $(ls -l work/dist/bin/rlvm | awk '{print $5}') bytes; $(work/dist/bin/rlvm --version | sed -n 1,2p | paste -sd'|' -)"
echo "binary: dynamic dependencies: $(ldd work/dist/bin/rlvm | awk '{print $1}' | paste -sd' ' -)"
if [ "$force_zlib" = 1 ]; then
  if ldd work/dist/bin/rlvm | grep -q 'libz\.so'; then
    echo "FAIL: zlib was to be linked statically, but the binary depends on libz.so"; fail=1
  else
    echo "zlib: linked statically from the library built by scripts/arena/build.sh"
  fi
fi
for t in good/init-prelude good/tutorial/001_basicDef bad/tutorial/002_badDef good/perf/app-lam; do
  f="$ROOT/work/arena-site/tests/$t.ndjson"
  if [ ! -f "$f" ]; then
    f="$(ls "$ROOT/work/arena-site/tests/${t%%/*}"/*/*.ndjson 2>/dev/null | head -n 1)"
    [ -n "$f" ] || { echo "no test export found for $t"; continue; }
  fi
  line="$("$ROOT/bench/measure.sh" --timeout 120 --in "$f" -c "$run_line" 2>/dev/null | tail -n 1)"
  python3 -I - "$f" "$line" "$strict" <<'PY' || fail=1
import json, sys
name = "/".join(sys.argv[1].split("/")[-3:])
try:
    m = json.loads(sys.argv[2])
except ValueError:
    print("FAIL: no measurement for %s" % name); sys.exit(1)
ins = m.get("instructions")
print("run: %-44s exit %s  %s instructions  wall %.3f s  rss %.1f MB" % (
    name, m["exit_code"], "n/a" if ins is None else format(ins, ","), m["wall_time_s"], m["max_rss_bytes"] / 2**20))
want = 0 if "/good/" in sys.argv[1] else 1
strict = sys.argv[3] == "1"
if m["exit_code"] == want:
    pass
elif m["exit_code"] == 2 and not strict:
    print("note: declined (expected exit status %d); allowed without --strict" % want)
else:
    print("FAIL: expected exit status %d (%s)%s" % (
        want, "accept" if want == 0 else "reject", "" if strict else " or 2 (decline)")); sys.exit(1)
PY
done
exit "$fail"
EOF
chmod +x "$E2E/inner.sh"
run_rc=0
"$ROOT/bench/arena-docker.sh" --arena-limits --no-network -w "$SRC" \
    "$E2E/inner.sh" "$ROOT" "$run_line" "$force_zlib" "$strict" 2>&1 | tee -a "$LOG" || run_rc=$?
if [ "$run_rc" = 0 ]; then
  say "PASS (log: $LOG)"
else
  say "FAIL (log: $LOG)"
  exit 1
fi
