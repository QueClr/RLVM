#!/usr/bin/env python3
"""bench/baselines/gen-wrappers.py - write bench/baselines/<name>.sh for arena checkers.

    bench/baselines/gen-wrappers.py [--arena DIR] [--force] NAME [NAME...]

For every NAME (a checker of the arena, checkers/NAME.yaml in the working copy
work/arena-checkers) that has been built with bench/baselines/build-checker.sh,
writes the wrapper bench/baselines/NAME.sh:

    bench/baselines/NAME.sh EXPORT.ndjson        (inside the rlvm-arena container)

The wrapper runs the checker the way the arena's lka.py does
(run_checker_on_test): the `run:` command of the yaml, verbatim, through
`sh -c`, with the working directory set to the checker's build directory
(_build/checkers/NAME/src, or _build/checkers/NAME for a checker without
url/dir), the export's absolute path in $IN and LC_ALL=C. Its exit status is
the command's: 0 accept, 1 reject, 2 decline, anything else an error.

The run command is copied from the yaml by this script, not typed by hand, so
flags and thread counts are the arena's. bench/baselines/MANIFEST.json lists
what was generated (revision, threads, run command, directories).

Runs on the host or in the container; only reads yaml and writes small files.
"""
import argparse
import json
import os
import sys
from pathlib import Path

import yaml

SELF_DIR = Path(__file__).resolve().parent
ROOT = SELF_DIR.parent.parent

TEMPLATE = """#!/bin/sh
# GENERATED by bench/baselines/gen-wrappers.py from checkers/{name}.yaml of the
# arena at {arena_rev}. Do not edit; regenerate instead.
#
#   bench/baselines/{name}.sh EXPORT.ndjson      (inside the rlvm-arena container)
#
# Runs the arena checker "{name}" ({version}) exactly as the arena does: the
# yaml's run command through `sh -c`, cwd = its build directory, $IN = the
# export, LC_ALL=C. Exit status: 0 accept, 1 reject, 2 decline, other = error
# (64: wrong usage, 66: no such export, 70: the checker is not built; the
# arena never runs a checker on a missing file, and the checkers' own answers
# to one range from "rejected" to "declined").
[ "$#" -eq 1 ] || {{ echo "usage: $0 EXPORT.ndjson" >&2; exit 64; }}
case "$1" in /*) IN="$1" ;; *) IN="$PWD/$1" ;; esac
[ -f "$IN" ] && [ -r "$IN" ] || {{ echo "$0: cannot read $IN" >&2; exit 66; }}
case "$0" in */*) here="${{0%/*}}" ;; *) here=. ;; esac
LC_ALL=C
export IN LC_ALL
cd "$here/../../{rel_dir}" 2>/dev/null || {{ echo "$0: {rel_dir} not found; build it with bench/baselines/build-checker.sh {name}" >&2; exit 70; }}
exec sh -c '{run}'
"""


def sh_single_quote_body(text: str) -> str:
    return text.replace("'", "'\\''")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("names", nargs="+", metavar="NAME")
    ap.add_argument("--arena", default=str(ROOT / "work" / "arena-checkers"),
                    help="working copy of the arena (default: work/arena-checkers)")
    ap.add_argument("--force", action="store_true",
                    help="write the wrapper even if the build directory does not exist")
    args = ap.parse_args()

    arena = Path(args.arena).resolve()
    head = arena / ".git" / "HEAD"
    arena_rev = head.read_text().strip() if head.exists() else "unknown"
    if arena_rev.startswith("ref:"):
        ref = arena / ".git" / arena_rev.split(None, 1)[1]
        arena_rev = ref.read_text().strip() if ref.exists() else arena_rev

    manifest_path = SELF_DIR / "MANIFEST.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}

    rc = 0
    for name in args.names:
        yml = arena / "checkers" / f"{name}.yaml"
        if not yml.exists():
            print(f"{name}: no such checker ({yml})", file=sys.stderr)
            rc = 1
            continue
        cfg = yaml.safe_load(yml.read_text())
        # lka.py: git repos and local dirs live in <checker>/src, the rest in <checker>
        sub = "src" if (cfg.get("url") or cfg.get("dir")) else ""
        build_dir = arena / "_build" / "checkers" / name / sub
        if not build_dir.is_dir() and not args.force:
            print(f"{name}: {build_dir} does not exist (not built?); skipped", file=sys.stderr)
            rc = 1
            continue
        rel_dir = os.path.relpath(build_dir, ROOT)
        # as lka.py derives it: the yaml's version, else "<ref> (<rev7>)", else "<rev7>"
        rev7 = (cfg.get("rev") or "")[:7]
        ref = cfg.get("ref")
        version = cfg.get("version") or (
            f"{ref} ({rev7})" if rev7 and ref and ref not in ("master", "main") else rev7) or "unknown"
        run = cfg["run"].rstrip("\n")
        wrapper = SELF_DIR / f"{name}.sh"
        text = TEMPLATE.format(
            name=name,
            arena_rev=arena_rev,
            version=f"version {version}",
            rel_dir=rel_dir,
            run=sh_single_quote_body(run),
        )
        # Replace atomically, and only if something changed: a measurement may be
        # executing the wrapper right now, and must never see a half-written file.
        if not wrapper.exists() or wrapper.read_text() != text:
            tmp = wrapper.with_name(f".{name}.sh.tmp")
            tmp.write_text(text)
            tmp.chmod(0o755)
            os.replace(tmp, wrapper)
            state = "wrote"
        else:
            state = "unchanged"
        manifest[name] = {
            "wrapper": f"bench/baselines/{name}.sh",
            "checker_dir": rel_dir,
            "run": cfg["run"],
            # the yaml's `threads` (CPU slots the arena's parallel runner reserves);
            # absent means 1 slot, whatever the run command itself asks for
            "yaml_threads": cfg.get("threads"),
            "language": cfg.get("language"),
            "url": cfg.get("url"),
            "ref": cfg.get("ref"),
            "rev": cfg.get("rev"),
            "version": str(version),
            "arena_rev": arena_rev,
        }
        print(f"{name}: {state} {wrapper.relative_to(ROOT)}")

    manifest_path.write_text(json.dumps(dict(sorted(manifest.items())), indent=2) + "\n")
    return rc


if __name__ == "__main__":
    sys.exit(main())
