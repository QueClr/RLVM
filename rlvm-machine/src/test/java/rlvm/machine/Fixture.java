    /** Project root: system property {@code rlvm.root}, else the parent of the working directory. */
    static Path root() {
        String r = System.getProperty("rlvm.root");
        return (r != null ? Path.of(r) : Path.of("..")).toAbsolutePath().normalize();
    }

    /** True if the file (relative to the project root) exists; tests on corpora skip themselves otherwise. */
