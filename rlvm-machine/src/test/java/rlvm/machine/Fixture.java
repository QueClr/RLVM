    /** Builds the store and the machine. Called automatically by the first use. */
    void seal() {
        if (sealed) {
            return;
        }
        for (int i = 0; i < specs.size(); i++) {
            Spec s = specs.get(i);
            if (s.kind == DeclKind.INDUCT && s.rec == null) {
                s.rec = generateRecursor(specs.subList(0, i + 1), s);
            }
        }
        w = new World();
        build(w, specs, null);
        store = w.store;
        ctx = w.ctx;
        sealed = true;
        engine = new MachineEngine(store, EngineConfig.defaults());
        session = (MachineSession) engine.newSession(ctx);
        m = session.m;
        m.beginDecl(Integer.MAX_VALUE, -1, Op.FUEL_UNLIMITED, Long.MAX_VALUE);
    }

    private void build(World world, List<Spec> list, Spec partial) {
        World saved = w;
        w = world; // the Sexp sink writes into this world
        try {
            for (String str : stringLits) {
                byte[] b = str.getBytes(StandardCharsets.UTF_8);
                world.strings.put(str, world.store.lits().addString(b, 0, b.length));
            }
            for (Spec s : list) {
                if (s.kind == DeclKind.INDUCT) {
                    writeBlock(world, s, s == partial);
                } else {
                    int cid = world.sb.beginDeclaration(s.kind, world.name(s.name), world.names(s.lparams));
                    if (cid == 0) {
                        throw new IllegalArgumentException("duplicate declaration " + s.name);
                    }
                    int ty = Sexp.term(s.type, this);
                    int val = s.sharedValue != null ? world.decls.value(world.cid(s.sharedValue))
                            : s.value == null ? 0 : Sexp.term(s.value, this);
                    world.sb.endDeclaration(cid, ty, val, s.hint);
                }
            }
            world.sb.finish();
            for (Object[] sp : specials) {
                int c = world.store.names().constOf(world.name((String) sp[1]));
                if (c > 0) {
                    world.store.specials().bind((Integer) sp[0], c, (Integer) sp[2]);
                }
            }
            world.store.publishEnv(world.store.loadedUnits());
            world.bindings.freeze();
            world.frozen = true;
            world.ctx = world.bindings.newWorkerContext(0, world.store, RunSignals.NONE, 1L << 30);
            world.lv = world.ctx.levels;
            world.ls = world.ctx.lists;
        } finally {
            w = saved;
        }
    }

    /** The elimination universe the official kernel picks: the first of u, u_1, u_2, .. that is not a parameter. */
    private static String elimName(String lparams) {
        List<String> used = Arrays.asList(lparams.trim().replace(',', ' ').split("\\s+"));
        String u = "u";
        for (int i = 1; used.contains(u); i++) {
            u = "u_" + i;
        }
        return u;
    }

    private void writeBlock(World world, Spec s, boolean partial) {
        StoreBuilder sb = world.sb;
        DeclTable decls = world.decls;
        sb.beginBlock();
        int lp = world.names(s.lparams);
        int ind = sb.claimMember(DeclKind.INDUCT, world.name(s.name), lp);
        int n = s.ctors.size();
        int[] ctorCids = new int[n];
        for (int i = 0; i < n; i++) {
            ctorCids[i] = sb.claimMember(DeclKind.CTOR, world.name(s.ctors.get(i)[0]), lp);
        }
        String recLparams = partial ? elimName(s.lparams) + " " + s.lparams : s.rec.lparams;
        int rec = sb.claimMember(DeclKind.REC, world.name(s.name + ".rec"), world.names(recLparams));
        if (ind == 0 || rec == 0) {
            throw new IllegalArgumentException("duplicate declaration " + s.name);
        }
        sb.setMemberType(ind, Sexp.term(s.type, this));
        for (int i = 0; i < n; i++) {
            sb.setMemberType(ctorCids[i], Sexp.term(s.ctors.get(i)[1], this));
        }
        if (partial) {
            // The block in flight: rlvm-inductive only needs the recursor's name and universe parameters.
            sb.setMemberType(rec, Sexp.term("Prop", this));
            sb.endBlock();
            return;
        }
        Rec r = s.rec;
        sb.setMemberType(rec, Sexp.term(r.type, this));
        int[] rules = new int[3 * r.ruleCtor.length];
        for (int i = 0; i < r.ruleCtor.length; i++) {
            rules[3 * i] = world.cid(r.ruleCtor[i]);
            rules[3 * i + 1] = r.ruleFields[i];
            rules[3 * i + 2] = Sexp.term(r.ruleRhs[i], this);
        }
        sb.endBlock();
        // What the environment pass commits (rlvm-admit EnvBuilder; R03 checklist item 52).
        int flags = (r.isRec ? DeclTable.IF_REC : 0) | (r.isReflexive ? DeclTable.IF_REFLEXIVE : 0);
        if (n == 1) {
            flags |= DeclTable.IF_ONE_CTOR;
            if (r.numIndices == 0 && !r.isRec) {
                flags |= DeclTable.IF_STRUCT_LIKE;
                if (r.ctorFields[0] == 0) {
                    flags |= DeclTable.IF_UNIT_LIKE;
                }
            }
        }
        decls.setInductive(ind, s.numParams, r.numIndices, ctorCids, n, new int[] {ind}, 1, flags, 0, rec);
        for (int i = 0; i < n; i++) {
            decls.setConstructor(ctorCids[i], ind, i, s.numParams, r.ctorFields[i]);
        }
        decls.setRecursor(rec, s.numParams, r.numIndices, r.numMotives, r.numMinors, r.k ? DeclTable.RF_K : 0, rules,
                r.ruleCtor.length, ind);
    }

    /**
     * The recursor of the last specification of {@code prefix}: a store with everything before it and
     * the block's types and constructors is built, {@code rlvm-inductive} generates the block with the
     * reference kernel, and the result is kept as text so that it can be written into the final store.
     */
    private Rec generateRecursor(List<Spec> prefix, Spec s) {
        World world = new World();
        build(world, prefix, s);
        DeclTable decls = world.decls;
        WorkerContext c = world.ctx;
        int ind = world.cid(s.name);
        int rec = world.cid(s.name + ".rec");
        int n = s.ctors.size();
        BlockInput in = new BlockInput();
        in.unit = decls.unit(ind);
        in.rank = decls.rank(ind);
        in.levelParams = decls.levelParams(ind);
        in.numParams = s.numParams;
        in.typeCount = 1;
        in.typeCid = new int[] {ind};
        in.typeName = new int[] {decls.name(ind)};
        in.typeType = new int[] {decls.type(ind)};
        in.typeCtorStart = new int[] {0};
        in.typeCtorCount = new int[] {n};
        in.ctorCount = n;
        in.ctorCid = new int[n];
        in.ctorName = new int[n];
        in.ctorType = new int[n];
        in.ctorClaimLevelParams = new int[n];
        in.ctorClaimInduct = new int[n];
        in.ctorClaimCidx = new long[n];
        in.ctorClaimNumParams = new long[n];
        in.ctorClaimNumFields = new long[n];
        for (int i = 0; i < n; i++) {
            int cc = world.cid(s.ctors.get(i)[0]);
            in.ctorCid[i] = cc;
            in.ctorName[i] = decls.name(cc);
            in.ctorType[i] = decls.type(cc);
            in.ctorClaimLevelParams[i] = in.levelParams;
            in.ctorClaimInduct[i] = in.typeName[0];
            in.ctorClaimCidx[i] = i;
            in.ctorClaimNumParams[i] = s.numParams;
        }
        in.recCount = 1;
        in.recCid = new int[] {rec};
        in.recName = new int[] {decls.name(rec)};
        in.recType = new int[] {decls.type(rec)};
        in.recLevelParams = new int[] {decls.levelParams(rec)};
        in.recAll = new int[] {c.lists.intern(in.typeName, 0, 1)};
        in.recNumParams = new long[1];
        in.recNumIndices = new long[1];
        in.recNumMotives = new long[1];
        in.recNumMinors = new long[1];
        in.recK = new boolean[1];
        in.recRuleCount = new int[1];
        in.recRuleCtorName = new int[][] {new int[0]};
        in.recRuleFields = new long[][] {new long[0]};
        in.recRuleRhs = new int[][] {new int[0]};
        in.consistent = true;

        KernelOps ops = new RefKernel(c, EngineConfig.defaults());
        ops.begin(in.rank, in.levelParams);
        GeneratedBlock gen = new GeneratedBlock();
        try {
            new InductiveAdmission(world.store, ops).generate(in, gen);
        } catch (RuntimeException e) {
            throw new IllegalArgumentException("inductive " + s.name + " is not admissible: " + e, e);
        }
        if (gen.numNested != 0 || gen.recCount != 1 || gen.declineReason != null) {
            throw new IllegalArgumentException("inductive " + s.name + ": nested blocks are not supported by the hand-built"
                    + " fixture (decline reason " + gen.declineReason + ")");
        }
        Rec r = new Rec();
        StringBuilder lp = new StringBuilder();
        for (int i = 0, k = c.lists.length(gen.recLevelParams); i < k; i++) {
            lp.append(i == 0 ? "" : " ").append(world.store.names().toString(c.lists.get(gen.recLevelParams, i)));
        }
        r.lparams = lp.toString();
        r.type = Show.term(c.terms, world.store, c.levels, c.lists, c.lits, gen.recType[0]);
        r.numIndices = gen.recNumIndices[0];
        r.numMotives = gen.recNumMotives;
        r.numMinors = gen.recNumMinors;
        r.k = gen.k;
        r.isRec = gen.isRec;
        r.isReflexive = gen.isReflexive;
        r.ctorFields = Arrays.copyOf(gen.ctorNumFields, n);
        int rules = gen.recRuleCount[0];
        r.ruleCtor = new String[rules];
        r.ruleFields = new int[rules];
        r.ruleRhs = new String[rules];
        for (int i = 0; i < rules; i++) {
            r.ruleCtor[i] = world.store.names().toString(decls.name(gen.recRuleCtor[0][i]));
            r.ruleFields[i] = gen.recRuleFields[0][i];
            r.ruleRhs[i] = Show.term(c.terms, world.store, c.levels, c.lists, c.lits, gen.recRuleRhs[0][i]);
        }
        return r;
    }

