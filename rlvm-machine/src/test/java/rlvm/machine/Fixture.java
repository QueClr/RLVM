    // The context of free variables and the judgments
    // ---------------------------------------------------------------------------------------------------

    /**
     * Opens a binder of the fixture's context: {@code name} is a loose bound variable of later terms and
     * is bound to a fresh free variable of the given type (a term over the context so far).
     *
     * @return the FVAR value
     */
    int fvar(String name, String type) {
        int ty = eval(term(type));
        int x = Scope.open(m, ty);
        if (x >= Op.SIG) {
            throw failure(x);
        }
        ctxNames.add(name);
        ctxTypes.add(ty);
        ctxVars.add(x);
        loadEnv();
        return x;
    }

    /** Closes the whole context. */
    void closeContext() {
        ctxNames.clear();
        ctxTypes.clear();
        ctxVars.clear();
        m.closeBindersAbove(0);
        m.ep = 0;
    }

    private void loadEnv() {
        int n = ctxVars.size();
        m.ep = 0;
        if (!m.ensureEnv(n)) {
            throw new IllegalStateException("environment slab full");
        }
        for (int i = 0; i < n; i++) {
            m.es[i] = ctxVars.get(i);
        }
        m.ep = n;
    }

    private MachineFailure failure(int signal) {
        int code = m.err;
        // The signal left the machine stacks as they were (H7): restore them and re-open the context,
        // which reproduces the same variables (ISA 2.8).
        m.abandon();
        m.err = 0;
        for (int i = 0; i < ctxVars.size(); i++) {
            int x = Scope.open(m, ctxTypes.get(i));
            if (x != ctxVars.get(i)) {
                throw new IllegalStateException("re-opening the context gave another variable: " + x + " for " + ctxVars.get(i));
            }
        }
        loadEnv();
        return new MachineFailure(code, signal);
    }

    /** Completes a judgment called at depth 0; a signal becomes a {@link MachineFailure}. */
    int run(int r) {
        r = m.drive(r);
        if (r >= Op.SIG) {
            throw failure(r);
        }
        return r;
    }

    int eval(int term) {
        seal();
        return run(Eval.eval(m, term, 0, ctxVars.size(), 0, 0));
    }

    /** EVAL under a substitution id (a term of a constant with universe parameters). */
    int eval(int term, int ls) {
        seal();
        return run(Eval.eval(m, term, 0, ctxVars.size(), ls, 0));
    }

    int force(int v) {
        return run(Eval.force(m, v, 0));
    }

    int apply(int f, int... args) {
        int xb = m.xp;
        if (!m.ensureScratch(args.length)) {
            throw new IllegalStateException("scratch full");
        }
        System.arraycopy(args, 0, m.X, xb, args.length);
        m.xp = xb + args.length;
        try {
            return run(Eval.apply(m, f, xb, args.length, 0));
        } finally {
            m.xp = xb;
        }
    }

    int inst(int pi, int x) {
        return run(Eval.inst(m, pi, x, 0));
    }

