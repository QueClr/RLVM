    /** A judgment ended with a signal: {@link #code} is the {@code MachineErrors} code, {@link #signal} ABORT or FATAL. */
    static final class MachineFailure extends RuntimeException {
        private static final long serialVersionUID = 1L;
        final int code;
        final int signal;

        MachineFailure(int code, int signal) {
            super(MachineErrors.name(code) + (signal == Op.FATAL ? " (fatal)" : " (abort)"));
            this.code = code;
            this.signal = signal;
        }
    }

    /** Outcome of running an engine over the units of a loaded export, in file order. */
    static final class Verdict {
        int outcome = Outcome.ACCEPT;
        /** First unit that was not accepted, or -1. */
        int unit = -1;
        Reason reason;
        String message = "";
        int units;

        @Override
        public String toString() {
            return Outcome.name(outcome) + (unit < 0 ? "" : " at unit " + unit + ": " + reason + ": " + message);
        }
    }

    /** Per-declaration comparison of the machine with the reference engine. */
    static final class DiffReport {
        int compared;
        int agree;
        /** The machine declined where the reference decided (incomplete, never wrong). */
        int declined;
        /** The machine accepted what the reference rejects. */
        int soundness;
        /** The machine rejected what the reference accepts. */
        int completeness;
        /**
         * The reference engine itself declined the unit (its memory budget, on a few good/perf tests): no
         * oracle for it. Not a difference and not counted in {@link #compared}; the comparison goes on
         * behind such a unit. {@link #clean()} is false, because the unit was not judged.
         */
        int referenceDeclined;
        final List<String> lines = new ArrayList<>();

        boolean clean() {
            return declined == 0 && soundness == 0 && completeness == 0 && referenceDeclined == 0;
        }

        @Override
        public String toString() {
            StringBuilder sb = new StringBuilder();
            sb.append(compared).append(" compared, ").append(agree).append(" agree, ").append(declined).append(" declined, ")
                    .append(soundness).append(" SOUNDNESS, ").append(completeness).append(" COMPLETENESS");
            if (referenceDeclined != 0) {
                sb.append(", ").append(referenceDeclined).append(" not judged (the reference declined)");
            }
            for (int i = 0; i < lines.size() && i < 40; i++) {
                sb.append('\n').append(lines.get(i));
            }
            return sb.toString();
        }
    }

