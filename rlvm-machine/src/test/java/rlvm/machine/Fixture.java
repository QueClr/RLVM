    /** Asserts that {@code body} ends with the machine error {@code code}. */
    void expectFail(int code, Runnable body) {
        try {
            body.run();
        } catch (MachineFailure e) {
            if (e.code != code) {
                throw new AssertionError("expected " + MachineErrors.name(code) + " but the judgment failed with "
                        + MachineErrors.name(e.code), e);
            }
            return;
        }
        throw new AssertionError("expected " + MachineErrors.name(code) + " but the judgment completed");
    }

