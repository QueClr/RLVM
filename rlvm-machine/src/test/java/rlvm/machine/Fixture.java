    /** One store being written or read. */
    private static final class World {
        final Bindings bindings = new Bindings(64);
        final Store store;
        final StoreBuilder sb;
        final DeclTable decls;
        final Map<String, Integer> strings = new HashMap<>();
        boolean frozen;
        WorkerContext ctx;
        LevelOps lv;
        IntLists ls;

        World() {
            store = new Store(1 << 16, bindings.baseLists(), bindings.baseLevelInfo());
            bindings.bindNames(store.names());
            sb = store.builder();
            decls = store.decls();
            lv = bindings.baseLevels();
            ls = bindings.baseLists();
        }

        int name(String dotted) {
            int id = 0;
            for (String part : dotted.split("\\.")) {
                byte[] b = part.getBytes(StandardCharsets.UTF_8);
                id = store.names().internStr(id, b, 0, b.length);
            }
            return id;
        }

        int names(String spaceSeparated) {
            String trimmed = spaceSeparated == null ? "" : spaceSeparated.trim().replace(',', ' ');
            if (trimmed.isEmpty()) {
                return IntLists.EMPTY;
            }
            String[] parts = trimmed.split("\\s+");
            int[] ids = new int[parts.length];
            for (int i = 0; i < parts.length; i++) {
                ids[i] = name(parts[i]);
            }
            return ls.intern(ids, 0, ids.length);
        }

        int cid(String name) {
            int c = store.names().constOf(name(name));
            if (c <= 0) {
                throw new IllegalArgumentException("no constant " + name);
            }
            return c;
        }
    }

