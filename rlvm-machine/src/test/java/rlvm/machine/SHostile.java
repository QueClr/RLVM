package rlvm.machine;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.net.URISyntaxException;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Predicate;
import java.util.zip.GZIPInputStream;
import rlvm.api.Outcome;

/**
 * The hostile exports of the independent soundness review (package S; {@code docs/design/review/soundness-machine.md}):
 * hand-written exports under {@code src/test/resources/s/}, each attacking one shortcut or memo of the machine,
 * with the verdict of the OFFICIAL checker ({@code leanchecker} 4.36.0) in {@code manifest.tsv}.
 *
 * <p>One export is judged in-process by M8's {@link Diff#compare} (real loader, environment pass, reference
 * engine and one machine lane) under a given switch set. What must hold for a row of the manifest:
 * <ul>
 *   <li>the reference engine's verdict of the file is the official one;
 *   <li>the machine never accepts a unit the reference engine rejects and never rejects one it accepts;
 *   <li>the machine's own verdict of the file (its first unit that is not accepted) is the official one; a
 *       decline of the machine is honest: it is reported and never fails a test.
 * </ul>
 * A row may carry KNOWN FINDINGS ({@code eager}, {@code warm}, {@code probes}, {@code facts}, {@code levels},
 * {@code bind} = findings E1-F1 .. E1-F7 of 2026-11-24: a bound variable typed by what it is bound to instead of by
 * its binder's declared domain; no row carries it: E1-F1 .. F3, F5, F6 are fixed and the rows of E1-F4 (accepted with
 * the switch {@code convexpect}) and E1-F7 are kind T rows, see below): the
 * switch (or, for {@code eager}, {@code levels} and {@code bind}, every configuration, v0 included) under which the published
 * machine still gives a verdict the official checker does not give. Such a violation is reported, not failed, by the fast tests, so that an open finding
 * of another package does not block publications; {@link SHostileSlowTest#noKnownFindingIsLeft} fails while
 * one is left. When the owner has fixed it, the mark is removed from the manifest and the row is strict.
 *
 * <p>KIND (owner's decision "practical", {@code docs/design/OWNER-NOTES.md} note 13, 2026-11-24): a row with the mark
 * {@code T} is a KIND T row - the statement of its planted declaration is derivable in the theory and the official
 * checker rejects it only through its own incompleteness, non-transitivity, cache order or object identity
 * ({@code docs/design/review/official-divergence.md} has the classes and the certificates). Such a row demands the
 * official verdict OR an accept of the machine; an accept is listed as tolerated. Every row without the mark is
 * strict: the official verdict (a kind F row - a statement that is not derivable - is always strict).
 *
 * <p>The exports are regenerated by {@code src/test/resources/s/gen/batch*.py} (builder {@code lk.py}) and judged
 * against the official checker, the reference engine and the machine through the launcher by
 * {@code gen/judge.py}; the plain files are in {@code work/soundness/exports/}.
 */
final class SHostile {
    private SHostile() {}

    /** The candidate default of staging step 1. */
    static final String STEP1 = "warm,gated,expect";

    /** One row of {@code manifest.tsv}. */
    static final class Row {
        final String name;
        /** {@code Outcome.ACCEPT} or {@code Outcome.REJECT}: what the official checker answers. */
        final int official;
        /**
         * {@code -}, or a comma list of marks: known findings ({@code eager}, {@code warm}, {@code probes}, {@code facts},
         * {@code levels}) and notes ({@code decline}: the pipeline declines the input by design; {@code eager-decline}:
         * the machine declines the unit that enters eager reduction, by design, M6-F26).
         */
        final String finding;
        final String attack;

        Row(String name, int official, String finding, String attack) {
            this.name = name;
            this.official = official;
            this.finding = finding;
            this.attack = attack;
        }

        /** True if the row carries this mark. */
        boolean marked(String mark) {
            for (String f : finding.split(",")) {
                if (f.equals(mark)) {
                    return true;
                }
            }
            return false;
        }

        /** True if a known finding of the row applies to a machine under this switch set. */
        boolean knownUnder(String switches) {
            for (String f : finding.split(",")) {
                if (f.equals("levels") || f.equals("eager") || f.equals("bind")
                        || ((f.equals("probes") || f.equals("facts") || f.equals("warm")) && has(switches, f))) {
                    return true;
                }
            }
            return false;
        }
    }

    private static boolean has(String switches, String name) {
        if (switches.equals("all")) {
            return true;
        }
        for (String s : switches.split(",")) {
            if (s.equals(name)) {
                return true;
            }
        }
        return false;
    }

    private static List<Row> rows;
    private static Path dir;

    /** The manifest, in file order. */
    static synchronized List<Row> rows() {
        if (rows == null) {
            List<Row> out = new ArrayList<>();
            try (InputStream in = SHostile.class.getResourceAsStream("/s/manifest.tsv")) {
                if (in == null) {
                    throw new IllegalStateException("no /s/manifest.tsv on the test class path");
                }
                for (String line : new String(in.readAllBytes(), StandardCharsets.UTF_8).split("\n")) {
                    if (line.isEmpty() || line.startsWith("#")) {
                        continue;
                    }
                    String[] f = line.split("\t", 4);
                    if (f.length != 4 || !(f[1].equals("accept") || f[1].equals("reject"))) {
                        throw new IllegalStateException("bad manifest line: " + line);
                    }
                    out.add(new Row(f[0], f[1].equals("accept") ? Outcome.ACCEPT : Outcome.REJECT, f[2], f[3]));
                }
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
            rows = out;
        }
        return rows;
    }

    /** The plain export of a row: the resource {@code /s/NAME.ndjson.gz} unpacked once into a temporary directory. */
    static synchronized String export(Row row) {
        try {
            if (dir == null) {
                dir = Files.createTempDirectory("rlvm-s-exports");
                final Path d = dir;
                Runtime.getRuntime().addShutdownHook(new Thread(() -> {
                    try (java.util.stream.Stream<Path> s = Files.list(d)) {
                        s.forEach(p -> p.toFile().delete());
                    } catch (IOException e) {
                        // best effort
                    }
                    d.toFile().delete();
                }));
            }
            Path out = dir.resolve(row.name + ".ndjson");
            if (!Files.exists(out)) {
                URL url = SHostile.class.getResource("/s/" + row.name + ".ndjson.gz");
                if (url == null) {
                    throw new IllegalStateException("no export for manifest row " + row.name);
                }
                try (InputStream in = new GZIPInputStream(Files.newInputStream(Path.of(url.toURI())))) {
                    Files.copy(in, out, StandardCopyOption.REPLACE_EXISTING);
                }
            }
            return out.toString();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        } catch (URISyntaxException e) {
            throw new IllegalStateException(e);
        }
    }

    /** What a lane found. */
    static final class Result {
        /** Violations that no known finding of the manifest covers: the test fails on these. */
        final List<String> unexpected = new ArrayList<>();
        /** Violations covered by a known finding (still open). */
        final List<String> known = new ArrayList<>();
        /** Rows whose known finding applies to the lane and that showed no violation. */
        final List<String> notReproduced = new ArrayList<>();
        /** Kind T rows (mark {@code T}) that the machine accepts although the official checker rejects them: tolerated, listed. */
        final List<String> tolerated = new ArrayList<>();
        /** Exports on which the machine declined where the official checker answers: honest, reported, never a failure. */
        final List<String> declines = new ArrayList<>();
        int judged;

        String report(String switches) {
            StringBuilder sb = new StringBuilder();
            sb.append("hostile exports under '").append(switches.isEmpty() ? "v0" : switches).append("': ").append(judged)
                    .append(" judged, ").append(unexpected.size()).append(" unexpected, ").append(known.size())
                    .append(" known findings still open, ").append(declines.size()).append(" declines of the machine, ")
                    .append(tolerated.size()).append(" kind T accepts (tolerated)");
            for (String s : unexpected) {
                sb.append("\n  UNEXPECTED ").append(s);
            }
            for (String s : known) {
                sb.append("\n  known      ").append(s);
            }
            for (String s : declines) {
                sb.append("\n  decline    ").append(s);
            }
            return sb.toString();
        }
    }

    /**
     * Judges the rows that {@code select} accepts with one machine lane under {@code switches} ("" = v0)
     * and the reference engine.
     */
    static Result run(String switches, Predicate<Row> select) {
        Result res = new Result();
        for (Row row : rows()) {
            if (!select.test(row)) {
                continue;
            }
            Diff.Options o = new Diff.Options();
            o.progress = false;
            o.config.switches(switches);
            o.config.checkMillis = 60_000;
            o.fileMillis = 180_000;
            Diff.FileResult r = Diff.compare(export(row), o);
            res.judged++;
            String v = violation(row, r);
            if (v == null) {
                if (row.knownUnder(switches)) {
                    res.notReproduced.add(row.name);
                }
                continue;
            }
            String line = row.name + " [official " + Outcome.name(row.official) + "]: " + v + " | attacks: " + row.attack;
            if (v.startsWith(TOLERATED)) {
                res.tolerated.add(line);
            } else if (v.startsWith(DECLINE)) {
                res.declines.add(line);
            } else if (row.knownUnder(switches)) {
                res.known.add("(" + row.finding + ") " + line);
            } else {
                res.unexpected.add(line);
            }
        }
        return res;
    }

    private static final String DECLINE = "the machine declines where the official checker answers: ";
    private static final String TOLERATED = "kind T accept (tolerated): ";

    /** Null if the comparison shows what the manifest row demands, else what is wrong (a decline starts with {@link #DECLINE}). */
    private static String violation(Row row, Diff.FileResult r) {
        if (r.status.equals("CRASH") || r.status.equals("TIMEOUT")) {
            return r.status + ": " + r.first;
        }
        boolean declineOk = row.marked("decline"); // the pipeline declines the input by design
        boolean eagerDecline = row.marked("eager-decline"); // the machine declines a unit that enters eager reduction
        // kind T (OWNER-NOTES 13, the practical policy): the statement of the planted declaration is derivable and the
        // official checker rejects it only through its own incompleteness, non-transitivity, cache order or object
        // identity; the row demands the official verdict OR an accept of the machine
        boolean kindT = row.marked("T") && row.official == Outcome.REJECT;
        if (r.soundness > 0) {
            return (kindT ? TOLERATED : "WRONG ACCEPT: ") + "the machine accepts a unit the reference engine rejects: " + r.first;
        }
        if (r.completeness > 0) {
            return "WRONG REJECT: the machine rejects a unit the reference engine accepts: " + r.first;
        }
        if (r.machineVerdict == Outcome.ACCEPT && row.official == Outcome.REJECT) {
            return (kindT ? TOLERATED : "WRONG ACCEPT: ") + "the machine accepts the file, the official checker rejects it"
                    + (r.refVerdict == Outcome.ACCEPT ? " (and the reference engine accepts it too)" : "");
        }
        if (r.machineVerdict == Outcome.REJECT && row.official == Outcome.ACCEPT) {
            return "WRONG REJECT: the machine rejects the file, the official checker accepts it: " + r.first;
        }
        if (r.refVerdict != row.official && !(declineOk && r.refVerdict == Outcome.DECLINE)) {
            return "the reference engine answers " + Outcome.name(r.refVerdict) + ", the official checker " + Outcome.name(row.official);
        }
        if (r.machineVerdict == Outcome.DECLINE && !declineOk && !eagerDecline) {
            return DECLINE + r.first;
        }
        return null;
    }
}
